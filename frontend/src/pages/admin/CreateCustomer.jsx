
import { useState } from "react";
import "./adminPages.css";

export default function CreateCustomer() {
  const [form, setForm] = useState({
    firstName: "",
    lastName: "",
    nid: "",
    mobileNumber: "",
    accountType: "SAVINGS",
  });

  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");
  const [created, setCreated] = useState(null);

  function handleChange(e) {
    setForm({
      ...form,
      [e.target.name]: e.target.value,
    });
  }

  async function handleSubmit(e) {
    e.preventDefault();

    setBusy(true);
    setMessage("");
    setError("");
    setCreated(null);

    try {
      const response = await fetch(
        "http://localhost:5000/api/admin/customers",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${localStorage.getItem("adminToken")}`,
          },
          body: JSON.stringify(form),
        }
      );

      const data = await response.json().catch(() => ({}));

      if (!response.ok || data.success === false) {
        throw new Error(
          data.message || "Customer creation failed."
        );
      }

      setMessage(data.message || "Customer created successfully.");

      setCreated(data.customer || data.data || data);

      setForm({
        firstName: "",
        lastName: "",
        nid: "",
        mobileNumber: "",
        accountType: "SAVINGS",
      });
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  }

  const accountNumber =
    created?.account?.accountNumber ||
    created?.accountNumber ||
    created?.accounts?.[0]?.accountNumber;

  return (
    <>
      <div className="page-heading">
        <div>
          <h2>Create Customer</h2>
          <p>Add a customer profile and linked account.</p>
        </div>
      </div>

      <div className="admin-card">
        <form className="admin-form" onSubmit={handleSubmit}>
          <div className="field">
            <label>First Name *</label>
            <input
              name="firstName"
              value={form.firstName}
              onChange={handleChange}
              required
              placeholder="First name"
            />
          </div>

          <div className="field">
            <label>Last Name *</label>
            <input
              name="lastName"
              value={form.lastName}
              onChange={handleChange}
              required
              placeholder="Last name"
            />
          </div>

          <div className="field">
            <label>NID Number *</label>
            <input
              name="nid"
              value={form.nid}
              onChange={handleChange}
              required
              placeholder="National ID number"
            />
          </div>

          <div className="field">
            <label>Mobile Number *</label>
            <input
              name="mobileNumber"
              type="tel"
              value={form.mobileNumber}
              onChange={handleChange}
              required
              placeholder="01XXXXXXXXX"
            />
          </div>

          <div className="field">
            <label>Account Type</label>
            <select
              name="accountType"
              value={form.accountType}
              onChange={handleChange}
            >
              <option value="SAVINGS">Savings</option>
              <option value="CURRENT">Current</option>
            </select>
          </div>

          <div className="field full">
            <p className="muted">
              Account number will be generated by the backend.
              The customer will set a password through the
              registration process.
            </p>
          </div>

          {error && (
            <div className="form-error field full">{error}</div>
          )}

          {message && (
            <div className="form-message field full">
              {message}

              {accountNumber && (
                <p>
                  <strong>Account Number: {accountNumber}</strong>
                </p>
              )}
            </div>
          )}

          <div className="form-actions">
            <button className="green-button" disabled={busy}>
              {busy ? "Creating..." : "Create Customer"}
            </button>

            <button
              type="button"
              className="soft-button"
              onClick={() => {
                setForm({
                  firstName: "",
                  lastName: "",
                  nid: "",
                  mobileNumber: "",
                  accountType: "SAVINGS",
                });
                setError("");
                setMessage("");
                setCreated(null);
              }}
            >
              Clear
            </button>
          </div>
        </form>
      </div>
    </>
  );
}
